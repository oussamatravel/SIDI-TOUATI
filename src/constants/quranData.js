// Helper to get total ayahs in a specific Hizb (1-60)
export const getHizbAyahCount = (hizbNum) => {
  if (hizbNum < 1 || hizbNum > 60) return 0;
  
  const start = HIZB_STARTS[hizbNum - 1];
  const end = (hizbNum === 60) ? [114, 6] : HIZB_STARTS[hizbNum];
  
  let total = 0;
  const startSurahIdx = start[0] - 1;
  const endSurahIdx = end[0] - 1;

  if (startSurahIdx === endSurahIdx) {
    // Both boundaries in same surah
    return end[1] - start[1];
  } else {
    // Spans multiple surahs
    // Ayahs in first surah
    total += (QURAN_DATA[startSurahIdx].ayahs - start[1] + 1);
    // Ayahs in middle surahs
    for (let i = startSurahIdx + 1; i < endSurahIdx; i++) {
      total += QURAN_DATA[i].ayahs;
    }
  }
  return total;
};

// Helper to get all ayahs in a specific Hizb (1-60) for mapping
export const getHizbAyahList = (hizbNum) => {
  if (hizbNum < 1 || hizbNum > 60) return [];
  
  const start = HIZB_STARTS[hizbNum - 1];
  const end = (hizbNum === 60) ? [114, 7] : HIZB_STARTS[hizbNum];
  
  const ayahs = [];
  const startSurahIdx = start[0] - 1;
  const endSurahIdx = end[0] - 1;

  if (startSurahIdx === endSurahIdx) {
    for (let i = start[1]; i < end[1]; i++) {
       ayahs.push({ surahId: start[0], ayah: i });
    }
  } else {
    // First surah
    for (let i = start[1]; i <= QURAN_DATA[startSurahIdx].ayahs; i++) {
        ayahs.push({ surahId: start[0], ayah: i });
    }
    // Middle surahs
    for (let s = startSurahIdx + 1; s < endSurahIdx; s++) {
        for (let i = 1; i <= QURAN_DATA[s].ayahs; i++) {
            ayahs.push({ surahId: s + 1, ayah: i });
        }
    }
    // Last surah
    for (let i = 1; i < end[1]; i++) {
        ayahs.push({ surahId: end[0], ayah: i });
    }
  }
  return ayahs;
};
